func TestLoggerMatchesLogSchema(t *testing.T) {
	var buf bytes.Buffer
	lv := new(slog.LevelVar)
	log := Logger(&buf, "gw-1", lv).With(slog.String("module", "test"))
	ctx := WithRequestID(t.Context(), "r-abc")
	log.WarnContext(ctx, "probe", slog.Group("detail", slog.Int("n", 1)))

	var line map[string]any
	if err := json.Unmarshal(buf.Bytes(), &line); err != nil {
		t.Fatalf("line is not JSON: %v (%s)", err, buf.String())
	}
	allowed := map[string]bool{"ts": true, "level": true, "service": true, "instance": true, "module": true,
		"tenant": true, "app": true, "request_id": true, "trace_id": true, "span_id": true,
		"map_version": true, "msg": true, "error": true, "detail": true}
	for k := range line {
		if !allowed[k] {
			t.Errorf("field %q is not allowed by log.schema.json", k)
		}
	}
	want := map[string]string{"level": "warn", "service": "gateway", "instance": "gw-1", "msg": "probe", "request_id": "r-abc"}
	for k, v := range want {
		if line[k] != v {
			t.Errorf("%s = %v, want %q", k, line[k], v)
		}
	}
	if !strings.HasSuffix(line["ts"].(string), "Z") {
		t.Errorf("ts not in UTC: %v", line["ts"])
	}
}

func TestLevelIsDynamic(t *testing.T) {
	var buf bytes.Buffer
	lv := new(slog.LevelVar)
	log := Logger(&buf, "gw-1", lv)
	log.Debug("hidden")
	lv.Set(slog.LevelDebug)
	log.Debug("visible")
	if strings.Contains(buf.String(), "hidden") || !strings.Contains(buf.String(), "visible") {
		t.Fatalf("level not applied at runtime: %s", buf.String())
	}
}

func TestRequestIDIgnoresClient(t *testing.T) {
	var seen string
	h := RequestIDMiddleware(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		seen = RequestID(r.Context())
	}))
	req := httptest.NewRequest("GET", "/", nil)
	req.Header.Set(HeaderRequestID, "r-chosen-by-client")
	rec := httptest.NewRecorder()
	h.ServeHTTP(rec, req)
	if seen == "" || seen == "r-chosen-by-client" {
		t.Fatalf("request_id not generated by the gateway: %q", seen)
	}
	if rec.Header().Get(HeaderRequestID) != seen {
		t.Fatal("request_id not returned in the response")
	}
}
