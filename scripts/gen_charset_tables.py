"""Generates gateway/internal/charset/tables.go: the upper half of the
single-byte encodings legacy sites use, from Python's codecs.

    python3 scripts/gen_charset_tables.py && gofmt -w gateway/internal/charset/tables.go
"""

CODECS = {
    "windows-1250": "cp1250", "windows-1251": "cp1251", "windows-1253": "cp1253", "windows-1254": "cp1254",
    "windows-1255": "cp1255", "windows-1256": "cp1256", "windows-1257": "cp1257", "windows-1258": "cp1258",
    "windows-874": "cp874",
    "iso-8859-2": "iso8859_2", "iso-8859-3": "iso8859_3", "iso-8859-4": "iso8859_4", "iso-8859-5": "iso8859_5",
    "iso-8859-6": "iso8859_6", "iso-8859-7": "iso8859_7", "iso-8859-8": "iso8859_8", "iso-8859-9": "iso8859_9",
    "iso-8859-10": "iso8859_10", "iso-8859-13": "iso8859_13", "iso-8859-14": "iso8859_14",
    "iso-8859-16": "iso8859_16", "koi8-r": "koi8_r", "koi8-u": "koi8_u", "ibm866": "cp866",
}
ALIASES = {
    "cp1250": "windows-1250", "x-cp1250": "windows-1250", "cp1251": "windows-1251", "x-cp1251": "windows-1251",
    "cp1253": "windows-1253", "cp1254": "windows-1254", "cp1255": "windows-1255", "cp1256": "windows-1256",
    "cp1257": "windows-1257", "cp1258": "windows-1258", "tis-620": "windows-874", "iso-8859-11": "windows-874",
    "latin2": "iso-8859-2", "l2": "iso-8859-2", "iso8859-2": "iso-8859-2", "latin3": "iso-8859-3",
    "latin4": "iso-8859-4", "cyrillic": "iso-8859-5", "iso8859-5": "iso-8859-5", "arabic": "iso-8859-6",
    "greek": "iso-8859-7", "iso8859-7": "iso-8859-7", "hebrew": "iso-8859-8", "iso-8859-8-i": "iso-8859-8",
    "latin5": "iso-8859-9", "iso8859-9": "iso-8859-9", "latin6": "iso-8859-10", "latin7": "iso-8859-13",
    "latin8": "iso-8859-14", "latin10": "iso-8859-16", "cp866": "ibm866", "866": "ibm866",
}


def main():
    out = ["// Code generated by scripts/gen_charset_tables.py; DO NOT EDIT.", "", "package charset", "",
           "// tables holds the upper half (0x80-0xFF) of single-byte encodings;",
           "// 0xFFFD marks a byte the encoding does not define.", "var tables = map[string]*[128]rune{"]
    for name, codec in CODECS.items():
        vals = []
        for b in range(0x80, 0x100):
            try:
                c = bytes([b]).decode(codec)
                vals.append(ord(c) if len(c) == 1 else 0xFFFD)
            except UnicodeDecodeError:
                vals.append(0xFFFD)
        out.append('\t"%s": {' % name)
        for i in range(0, 128, 8):
            out.append("\t\t" + ", ".join("0x%04X" % v for v in vals[i:i + 8]) + ",")
        out.append("\t},")
    out += ["}", "", "// tableAliases are other names of the encodings in tables.", "var tableAliases = map[string]string{"]
    out += ['\t"%s": "%s",' % kv for kv in ALIASES.items()]
    out.append("}")
    with open("gateway/internal/charset/tables.go", "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
